// dsh-web-sub — build script
// 1) copy the whole src tree into lib/ (single-file output is not an option:
//    the host imports server.js / store.js / providers/*)
// 2) wrap src/client-bundle.js into lib/client.js for the web module loader
// 3) emit locale/*.json for the plugin manager card

import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)))
const srcDir = join(root, 'src')
const libDir = join(root, 'lib')

rmSync(libDir, { recursive: true, force: true })
mkdirSync(libDir, { recursive: true })

/** Recursively copy a directory, skipping the client bundle. */
function copyTree(from, to, skip) {
  mkdirSync(to, { recursive: true })
  for (const entry of readdirSync(from)) {
    const source = join(from, entry)
    const target = join(to, entry)
    if (skip.has(relative(srcDir, source))) continue
    if (statSync(source).isDirectory()) copyTree(source, target, skip)
    else copyFileSync(source, target)
  }
}

copyTree(srcDir, libDir, new Set(['client-bundle.js']))

// The published entry point is lib/index.js; keep the src file as the source of truth.
writeFileSync(
  join(libDir, 'index.js'),
  '// Generated by scripts/build.mjs — edit src/host.js instead.\n' + readFileSync(join(srcDir, 'host.js'), 'utf-8'),
)

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'))
const clientSource = readFileSync(join(srcDir, 'client-bundle.js'), 'utf-8')

const wrapped = [
  `// Generated by scripts/build.mjs — edit src/client-bundle.js instead.`,
  `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {`,
  'var module = { exports: {} }; var exports = module.exports;',
  clientSource,
  'return module.exports;',
  '} });',
  '',
].join('\n')
writeFileSync(join(libDir, 'client.js'), wrapped)

mkdirSync(join(root, 'locale'), { recursive: true })
const locales = {
  en: {
    title: 'Web Chat Subscription',
    description: 'Bind your chat.deepseek.com and gemini.google.com sessions to use those models inside DSH.',
  },
  pt: {
    title: 'Assinatura Web Chat',
    description: 'Conecte suas sessões do chat.deepseek.com e do gemini.google.com para usar esses modelos dentro do DSH.',
  },
}
for (const [language, dictionary] of Object.entries(locales)) {
  writeFileSync(
    join(root, 'locale', `${language}.json`),
    JSON.stringify({ meta: { title: dictionary.title, description: dictionary.description } }, null, 2) + '\n',
  )
}

console.log('build OK -> lib/index.js, lib/client.js, locale/*.json')
